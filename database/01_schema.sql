-- =====================================================================
-- TecnoUAM - Sistema de préstamo de equipos tecnológicos
-- Script 1/2: estructura de la base de datos (PostgreSQL 14+)
--
-- Paso previo (una sola vez, conectado a la base "postgres"):
--     CREATE DATABASE tecno_uam_prestamos;
-- Luego ejecutar este archivo conectado a tecno_uam_prestamos:
--     psql -U postgres -d tecno_uam_prestamos -f database/01_schema.sql
--
-- Nota: el backend usa spring.jpa.hibernate.ddl-auto=update, por lo que también
-- crea estas tablas automáticamente. Este script permite reproducirlas manualmente.
-- =====================================================================

CREATE TABLE IF NOT EXISTS equipos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_patrimonial  VARCHAR(50)  NOT NULL,
    nombre              VARCHAR(100) NOT NULL,
    tipo                VARCHAR(20)  NOT NULL,
    estado              VARCHAR(20)  NOT NULL DEFAULT 'DISPONIBLE',
    CONSTRAINT uk_equipos_codigo_patrimonial UNIQUE (codigo_patrimonial),
    CONSTRAINT ck_equipos_tipo   CHECK (tipo   IN ('PORTATIL', 'PROYECTOR', 'TABLETA')),
    CONSTRAINT ck_equipos_estado CHECK (estado IN ('DISPONIBLE', 'PRESTADO'))
);

CREATE TABLE IF NOT EXISTS prestamos (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipo_id                   BIGINT       NOT NULL,
    nombre_solicitante          VARCHAR(120) NOT NULL,
    fecha_prestamo              DATE         NOT NULL,
    fecha_prevista_devolucion   DATE         NOT NULL,
    fecha_devolucion            DATE,
    estado                      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVO',
    -- Relación N:1 -> un equipo tiene muchos préstamos en su historial
    CONSTRAINT fk_prestamos_equipo FOREIGN KEY (equipo_id) REFERENCES equipos (id),
    CONSTRAINT ck_prestamos_estado CHECK (estado IN ('ACTIVO', 'DEVUELTO')),
    -- Regla: la fecha prevista de devolución no puede ser anterior a la fecha del préstamo
    CONSTRAINT ck_prestamos_fechas CHECK (fecha_prevista_devolucion >= fecha_prestamo)
);

-- Garantía a nivel de base de datos: un equipo solo puede tener UN préstamo ACTIVO a la vez
CREATE UNIQUE INDEX IF NOT EXISTS ux_prestamos_equipo_activo
    ON prestamos (equipo_id) WHERE estado = 'ACTIVO';

CREATE INDEX IF NOT EXISTS ix_prestamos_estado ON prestamos (estado);

CREATE TABLE IF NOT EXISTS usuarios (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username  VARCHAR(50)  NOT NULL,
    password  VARCHAR(100) NOT NULL,   -- hash BCrypt, nunca texto plano
    rol       VARCHAR(20)  NOT NULL,
    CONSTRAINT uk_usuarios_username UNIQUE (username),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('USER', 'ADMIN'))
);
